    B.append(h2("1.5 The System Under Study"))
    p("The subject of this paper is SMA-CLMPNet, a spatial-and-multi-"
      "excitation attention network for intra-frame video forgery detection, "
      "together with the complete implementation released alongside it. The "
      "implementation reads a subset of FaceForensics++, detects and crops "
      "faces with a Haar cascade, samples ten frames per video at "
      "128 x 128 resolution, and stacks twelve channels per frame — three "
      "RGB, three HSV, a local binary pattern map and edge responses — into "
      "a per-video tensor of shape (10, 128, 128, 12). Those tensors are "
      "cached once and reused by every model in the study.")
    p("The network itself consists of three Conv3D stages, each followed by "
      "a 'modified pooling' operation that averages a max-pooled and an "
      "average-pooled copy of the activation; a reshape into a spatial "
      "sequence; a joint spatial-and-channel attention module (SCAM); a "
      "second reshape; two parallel 128-unit LSTMs whose outputs are summed; "
      "a multi-excitation block (MUSE); and a two-layer fully connected head "
      "with batch normalisation and dropout terminating in a softmax over "
      "two classes. It has 2,258,534 trainable parameters. A single integer "
      "switch selects the ablation: with only MUSE active the model is "
      "MUSE-CLMPNet, with only SCAM active it is SCAM-CLMPNet, and with both "
      "active it is the proposed SMA-CLMPNet. A metaheuristic variant, "
      "SMA-CLMPNet-Opt, tunes hyperparameters with a population-based search "
      "from the MEALPY library " + cite("mealpy") + ".")
    p("The twelve-channel stacking deserves comment because it determines "
      "the ceiling of everything downstream. Three channels carry the "
      "original colour information. Three carry the same content in a "
      "hue-saturation-value decomposition, which is an invertible "
      "transformation of the first three and therefore adds no information, "
      "though it does change what a convolution with a small kernel can "
      "express cheaply. A local binary pattern channel encodes micro-texture "
      "as a comparison of each pixel against its neighbours, and the "
      "remaining channels carry gradient and edge responses. The stack is "
      "thus a mixture of raw appearance and hand-designed texture "
      "descriptors, computed independently per frame and concatenated. "
      "Nothing in the representation encodes motion, correspondence between "
      "frames, or the geometry of the face; the temporal axis is present "
      "only as an ordered stack that the model may or may not exploit.")
    p("The corpus is fifty videos. This number is not incidental and it is "
      "not a limitation to be acknowledged in a closing paragraph — it is "
      "the governing constraint on the entire study. A held-out partition "
      "under any protocol in the repository contains between five and "
      "thirty-one videos, so the granularity of any accuracy estimate is "
      "between three and twenty percentage points, and the confidence "
      "interval around a single fold's result spans a range wider than the "
      "differences the original work claims between models. Section 5.6 "
      "quantifies this: a perfect ten-out-of-ten result on a ten-video fold "
      "carries a 95% confidence interval extending down to 69.2%. Any "
      "protocol that reports a single fold's accuracy to two decimal places "
      "on a corpus this size is reporting noise with false precision.")
    p("The released comparison set contains six further systems — a plain "
      "deep convolutional network, an EfficientNet variant, a "
      "spatiotemporal inconsistency detector referred to as STIDNet, and a "
      "grey-level co-occurrence matrix baseline in the tradition of "
      + citet("haralick") + " — and the published results place "
      "SMA-CLMPNet above all of them at every training percentage examined.")

