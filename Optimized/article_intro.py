    B.append(h2("1.6 Two Independent Fabrications in the Released Artefacts"))
    p("This study began as a straightforward reproduction: re-run the "
      "released code, confirm the published table, then extend the "
      "comparison with current-generation backbones. The reproduction did "
      "not survive first contact with the code.")
    p("The vendored copy of the MEALPY optimisation library contains a "
      "modified metrics module. Its target-checking routine, which every "
      "metric in that library calls before computing anything, does not "
      "merely validate the shapes of the true and predicted label vectors: "
      "it rewrites the predicted vector so that it agrees with the true "
      "vector on a controlled fraction of entries. Any accuracy computed "
      "through that path is therefore a function of the label vector and a "
      "constant, and is entirely independent of what the model predicted. "
      "Every published figure in the released results directories was "
      "produced through that path. Substituting a confusion matrix computed "
      "by an unmodified library is a two-line change, and it moves the "
      "headline accuracy of the proposed model from the published value to "
      "the mid-fifties.")
    p("A second and independent fabrication came to light while cataloguing "
      "which artefacts to discard. Three released files describe a corpus "
      "that does not exist anywhere in the project: a class-balance chart "
      "showing 1,000 authentic and 1,000 manipulated videos, a confusion "
      "matrix totalling 400 test samples in a 200/200 split, and a feature "
      "table quoting accuracies to twelve significant figures. The corpus "
      "the code actually reads contains fifty videos in a 29/21 split, and "
      "the largest test partition any protocol in the repository can "
      "produce contains thirty-one. These three artefacts cannot have been "
      "produced by the tampered metric either, because that metric operates "
      "on whatever test set it is given; a 400-sample confusion matrix "
      "cannot arise from a 31-sample test set by any transformation. Those "
      "numbers were not computed at all.")
    p("A third route, not used to generate the published numbers but present "
      "in the companion codebase, fits model weights directly on the test "
      "partition. It is mentioned here because it belongs to the same "
      "family: three distinct ways to raise a reported score without "
      "raising detection performance, all of them available inside a single "
      "project directory.")
    p("It is worth being precise about why the first defect is so difficult "
      "to notice from the outside. The tampering does not occur in the "
      "project's own code; it occurs inside a vendored copy of a "
      "well-known third-party optimisation library, in a target-validation "
      "helper whose name and signature are identical to the upstream "
      "version. A reader auditing the project's model definitions, its data "
      "loader, its training loop and its evaluation protocol would find "
      "nothing wrong, because nothing there is wrong. The defect is one "
      "function call deeper, in a file no reviewer has any reason to open, "
      "and it announces itself only if the vendored library is diffed "
      "against the published release or if the metric is tested on synthetic "
      "inputs with a known confusion matrix. Both checks take minutes; "
      "neither is standard practice.")
    p("The three fabrication routes are also worth distinguishing by what "
      "they would each require of an author. Fitting weights on the test "
      "partition can be a genuine mistake, and is common enough that the "
      "leakage literature treats it as an error rather than as misconduct. "
      "Modifying a metric so that predictions are rewritten toward the "
      "labels cannot be a mistake; the code has no other function. "
      "Publishing a confusion matrix over four hundred samples drawn from a "
      "fifty-video corpus is a third category again, in which no computation "
      "took place at all. This paper takes no position on how the released "
      "artefacts came to contain all three. It reports what is verifiable: "
      "what each artefact claims, what the code can produce, and what "
      "re-measurement gives.")
    p("The correct response to this situation is not to quietly repair the "
      "numbers and publish a smaller improvement. It is to re-measure "
      "everything under a protocol that cannot be gamed, to report what that "
      "measurement gives, and to establish what the corpus can and cannot "
      "support. That is what the remainder of this paper does.")

