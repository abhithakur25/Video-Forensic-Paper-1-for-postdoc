    B.append(h2("1.3 Manipulation Families and the Difficulty of Intra-frame "
                "Forgery"))
    p("Video manipulation is conventionally partitioned into inter-frame and "
      "intra-frame families. Inter-frame forgery alters the sequence itself: "
      "frames are deleted to compress a timeline, duplicated to extend one, "
      "inserted from another source, or shuffled to reorder events. Because "
      "these operations disturb the temporal statistics of the encoded "
      "stream, they leave characteristic traces in motion residuals, "
      "prediction errors and quantisation patterns, and a mature body of "
      "work exploits exactly those traces " + cite("sitara", "kingra",
                                                   "fadl") + ". "
      "Intra-frame forgery leaves the frame ordering intact and instead "
      "rewrites content inside individual frames — most prominently by "
      "replacing a face while preserving pose, expression and illumination.")
    p("Intra-frame manipulation is the harder problem for three compounding "
      "reasons. First, the manipulated region is small relative to the "
      "frame; a face occupies a few percent of the pixels in a typical "
      "shot, so any detector operating on whole frames is looking for a "
      "sparse signal inside a large amount of unmodified content. Second, "
      "modern synthesis pipelines are explicitly optimised to remove exactly "
      "the artefacts that early detectors keyed on: blending seams, colour "
      "mismatch, resolution discontinuities and warping residuals are all "
      "targets of the generator's own loss. Third, and most importantly for "
      "the present work, the surviving evidence is largely temporal rather "
      "than spatial. A face swapped frame by frame is individually "
      "plausible in each frame and jointly implausible across frames: the "
      "identity flickers at the sub-pixel level, the blending boundary "
      "breathes, and physiological regularities such as blink rate and gaze "
      "trajectory drift out of their natural distributions.")
    p("This observation is what motivates the entire spatiotemporal branch "
      "of the literature. " + citet("guera") + " showed early that a "
      "convolutional feature extractor followed by a recurrent aggregator "
      "detects manipulations that per-frame classification misses. "
      + citet("sabir") + " made the recurrence explicit over aligned face "
      "crops. " + citet("amerini") + " showed that optical-flow fields "
      "carry discriminative structure that raw pixels do not. "
      + citet("haliassos") + " demonstrated that a network pre-trained to "
      "read lip movement transfers to forgery detection because it has "
      "already learned what natural facial dynamics look like. "
      + citet("ftcn") + " isolated temporal coherence as the generalising "
      "cue. " + citet("stil") + " formalised the idea as a pair of "
      "modules — a Temporal Inconsistency Module and an Information "
      "Supplement Module — that can be inserted into an otherwise ordinary "
      "backbone, and " + citet("istvt") + " and " + citet("tall") + " "
      "carried it into transformer architectures.")
    p("Compression complicates all of this in a way that is easy to "
      "underestimate. Every distribution channel re-encodes, and lossy "
      "video compression is designed to discard exactly the high-frequency, "
      "low-energy content in which manipulation residuals live. A cue that "
      "is clearly present in a raw manipulated frame may be entirely absent "
      "two re-encodings later, while the semantic content a human observer "
      "uses remains intact. This produces the counter-intuitive situation "
      "that detector accuracy falls as perceptual quality falls, even though "
      "the manipulation becomes no more convincing to a viewer. It also "
      "means a detector's accuracy is not a property of the detector alone "
      "but of the detector and the compression history of the material it is "
      "applied to — a dependency almost never reported. The corpus used in "
      "this study is drawn from compressed source material, which is "
      "realistic, and which places a real limit on what any spatial cue can "
      "contribute.")
    p("The system studied in this paper belongs to that branch. It combines "
      "a three-dimensional convolutional trunk, a joint spatial-and-channel "
      "attention block, a recurrent aggregator and a multi-excitation head, "
      "and it is designed on precisely the premise just described: that the "
      "residue of an intra-frame manipulation is a temporal inconsistency "
      "rather than a spatial artefact.")

