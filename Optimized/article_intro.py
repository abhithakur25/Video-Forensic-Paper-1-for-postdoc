    B.append(h2("1.4 Why Benchmark Accuracy and Deployed Reliability Diverge"))
    p("Before describing the system, it is worth being explicit about the "
      "mechanisms that separate a published accuracy from a trustworthy one, "
      "because the audit reported in this paper found two of them operating "
      "simultaneously and a third latent in the released code.")
    p("The first mechanism is optimistic evaluation design. When "
      "hyperparameters, feature scalings, decision thresholds, early-stopping "
      "epochs or model families are chosen using data that later appears in "
      "the reported test set, the reported number measures how well the "
      "choice fitted that set rather than how well the model generalises. "
      + citet("cawley") + " analysed this precisely and showed that the "
      "resulting bias is large enough to reverse published rankings; "
      + citet("kapoor") + " catalogued the same failure across dozens of "
      "fields and found it to be the single most common defect in "
      "machine-learning-based science.")
    p("The second mechanism is small-sample variance. On a corpus of a few "
      "dozen videos, the standard error of an accuracy estimate is measured "
      "in tens of percentage points, so an apparently decisive gap between "
      "two methods can be pure sampling noise. " + citet("varoquaux") + " "
      "quantified the effect in neuroimaging, " + citet("vabalas") + " in "
      "clinical prediction, and " + citet("bouthillier") + " showed that "
      "even the seed of the random number generator moves benchmark results "
      "by more than the improvements typically claimed over them. Related "
      "to this, " + citet("combrisson") + " demonstrated that the nominal "
      "50% chance line is the wrong reference on small or imbalanced "
      "samples: the empirical distribution of accuracy under a true null "
      "extends well above it, so a score of 60% or 65% may be entirely "
      "consistent with a model that has learned nothing.")
    p("The third mechanism is the one that motivated this study. It is not "
      "an evaluation-design error at all but a defect in the scoring code "
      "itself. If the function that computes the confusion matrix is "
      "modified so that it alters the predictions before comparing them "
      "against the labels, then every downstream metric — accuracy, "
      "sensitivity, specificity, precision, F1 and any curve derived from "
      "them — becomes a function of the labels rather than of the model. "
      "No amount of careful protocol design detects this, because the "
      "protocol is not what is broken. The only way to find it is to read "
      "the scoring code.")
    p("These three mechanisms are ordered by severity and, unfortunately, in "
      "reverse order of how often they are checked. Reviewers routinely "
      "interrogate splits and baselines; they rarely open the metrics "
      "module.")
    p("A fourth mechanism deserves mention because it is entirely innocent "
      "in intent and nonetheless produces the same outcome. On an imbalanced "
      "corpus, several standard summary statistics reward a model that has "
      "learned nothing. If 58% of the videos are authentic, a classifier "
      "that answers 'authentic' unconditionally achieves 58% accuracy, a "
      "recall of 1.00 on the majority class, and an F1 score above 0.73. "
      "Each of those numbers, reported on its own, reads as a functioning "
      "detector. Only specificity — the fraction of manipulated videos "
      "correctly identified — exposes the degeneracy, and specificity is the "
      "statistic most often omitted from summary tables. Several models in "
      "the cohort re-measured for this paper exhibit exactly this pattern, "
      "and it is the reason every table in Section 5 reports specificity and "
      "balanced accuracy alongside accuracy rather than in place of it.")
    p("The four mechanisms interact multiplicatively rather than additively. "
      "A degenerate classifier scored on an imbalanced corpus by a tampered "
      "metric, with its hyperparameters selected on the reporting set, "
      "produces a number that has essentially no relationship to detection "
      "performance and every appearance of a strong result. Disentangling "
      "them requires measuring each separately, which is what the "
      "experimental design of this paper is organised to do: the corrected "
      "metric isolates the third mechanism, the nested protocol isolates the "
      "first, the permutation test isolates the second, and reporting "
      "specificity isolates the fourth.")

