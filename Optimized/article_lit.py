    B.append(h2("2.5 Attention Mechanisms and the SCAM/MUSE Lineage"))
    p("Both attention blocks in the model studied here descend from an "
      "identifiable line of work, and understanding that line is necessary "
      "to interpret the ablation results in Section 5.")
    p(citet("senet") + " introduced channel attention in its modern form: "
      "pool each feature map to a scalar, pass the resulting vector through "
      "a bottleneck multilayer perceptron, and use the sigmoid output to "
      "rescale the channels. The block adds negligible computation and "
      "improved every backbone it was added to, which is why it propagated "
      "so quickly. " + citet("cbam") + " added the complementary spatial "
      "branch — pool across channels rather than across space, convolve the "
      "resulting two-channel map with a large kernel, and gate spatially — "
      "and applied the two branches in sequence. The SCAM module in the "
      "network studied here is a joint spatial-and-channel formulation of "
      "exactly this design, and the implementation follows CBAM's structure "
      "closely: global average and max pooling into a shared MLP for the "
      "channel gate, channel-wise average and max into a large-kernel "
      "convolution for the spatial gate.")
    p(citet("nonlocal") + " provided the other half of the vocabulary, "
      "generalising self-attention to a non-local operator that relates "
      "every position to every other position in space and time, and "
      "demonstrating that a small number of such blocks substantially "
      "improves video recognition. " + citet("mat") + " applied multi-"
      "attentional design specifically to deepfake detection, arguing that "
      "forgery detection is a fine-grained classification problem in which "
      "multiple attention heads should attend to different local regions, "
      "and combining that with textural feature enhancement.")
    p("There is a further reason to be careful about attention modules "
      "specifically, which the ablation in Section 5.3 illustrates. An "
      "attention block is a multiplicative gate: it produces coefficients in "
      "(0, 1) and rescales its input by them. If the features arriving at "
      "the gate carry no class-discriminative structure, the gate has "
      "nothing to select and its output is a smoothly rescaled copy of a "
      "signal that was already uninformative. The block does not fail "
      "loudly in that situation — it trains without error, its gradients are "
      "well behaved, and its coefficients settle to plausible-looking values "
      "— so its presence in an architecture diagram is no evidence that it "
      "contributed. This is why an attention ablation must be read together "
      "with an absolute measure of whether the surrounding model learned at "
      "all, and why the tables in Section 5 pair every ablation figure with "
      "the specificity of the same run.")
    p("The MUSE block in the studied network is a multi-excitation module "
      "operating on the 128-dimensional recurrent state: several excitation "
      "paths are computed and combined by averaging, with an ELU "
      "nonlinearity and light dropout " + cite("dropout") + ". "
      "Architecturally it is a squeeze-and-excitation variant applied after "
      "temporal aggregation rather than within the convolutional trunk.")
    p("This lineage sets a clear expectation for the ablation. Both blocks "
      "are, in the literature they come from, reliable small improvements. "
      "If neither the SCAM-only nor the MUSE-only variant differs "
      "measurably from the full model, and if none of the three differs "
      "measurably from a constant classifier, the natural inference is not "
      "that attention is useless in general but that no gradient signal "
      "reached the blocks — that the pipeline never learned anything for "
      "them to modulate. Section 5.3 reports exactly this pattern.")

