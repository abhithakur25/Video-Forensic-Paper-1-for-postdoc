    B.append(h2("2.7 Metaheuristic Optimisation in Forensic Pipelines"))
    p("The released project tunes its proposed model with a population-based "
      "metaheuristic drawn from the MEALPY library " + cite("mealpy") + ", "
      "which collects a large number of nature-inspired optimisers behind a "
      "common interface. Metaheuristic hyperparameter tuning is widespread "
      "in applied forensics papers, and it carries two well-understood "
      "risks that are worth stating explicitly because both are visible in "
      "this project.")
    p("The first is theoretical. " + citet("nfl") + " proved that averaged "
      "over all objective functions no search algorithm outperforms any "
      "other, so a metaheuristic's advantage on a particular problem is a "
      "claim about the match between the algorithm's bias and that "
      "problem's structure — a claim requiring evidence rather than a "
      "property the algorithm carries with it. The second is procedural. A "
      "population-based search evaluates hundreds of candidate "
      "configurations; if the fitness function evaluates on the data later "
      "used for reporting, the search is a highly efficient mechanism for "
      "selecting the configuration that best fits that particular sample, "
      "which is the selection bias " + citet("cawley") + " analyses. When "
      "the fitness function is additionally computed by a tampered metric, "
      "the search optimises the tampering. Section 5.2 reports the "
      "metaheuristically tuned variant under the corrected protocol.")
    p("There is also a question of evidential value that applies regardless "
      "of protocol. A metaheuristic search over a discrete hyperparameter "
      "grid on a fifty-video corpus evaluates its candidates against an "
      "objective whose sampling noise, by the analysis of "
      + citet("varoquaux") + " and " + citet("bouthillier") + ", exceeds "
      "the differences between most of the candidates. Under those "
      "conditions the search converges reliably — populations always "
      "converge — but what it converges to is the configuration that "
      "happened to suit the particular resampling draws it was scored on. "
      "Re-running the same search under a different seed selects a "
      "different configuration with an equally good reported fitness. The "
      "appropriate response is not to abandon the search but to report the "
      "spread across seeds rather than the best single outcome, and to "
      "select the configuration inside the training folds so that the "
      "reported score is at least unbiased. The protocol used in Section 5 "
      "does the latter; the original work does neither.")

