      "one part along the temporal axis, differences it against the "
      "unshifted part, and learns an attention map over the resulting "
      "difference tensor, so that the network is presented with frame-to-"
      "frame change as a first-class input rather than having to infer it. "
      "The Information Supplement Module restores spatial detail that the "
