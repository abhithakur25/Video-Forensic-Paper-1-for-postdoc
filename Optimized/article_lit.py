    B.append(h2("2.9 Leakage, Reproducibility and Research Integrity"))
    p(citet("ioannidis") + " gave the field-independent argument that in "
      "research areas combining small samples, small effects, analytic "
      "flexibility and strong incentives, the majority of published positive "
      "findings will be false. Every one of those four conditions holds for "
      "small-corpus forgery detection.")
    p(citet("kapoor") + " provided the machine-learning-specific version, "
      "auditing 294 papers across seventeen fields and finding data leakage "
      "in a large fraction of them, with a taxonomy that names the exact "
      "failures relevant here: no clean separation between training and test "
      "data, preprocessing performed on the full dataset before splitting, "
      "feature selection using test labels, and model selection on the "
      "reporting set. " + citet("gundersen") + " surveyed reproducibility "
      "in artificial intelligence research and found that a small minority "
      "of papers document enough to permit independent reproduction, with "
      "code and data availability the most common gaps. "
      + citet("cawley") + " supplies the quantitative core: selection bias "
      "in performance evaluation, arising when the same data both selects "
      "and scores, is large enough to invert published rankings.")
    p("Two practical consequences follow for reproduction attempts, and both "
      "are adopted as working procedure in this study. The first is that "
      "a released metric implementation must be treated as an untrusted "
      "input until it has been checked. The check is inexpensive: construct "
      "label and prediction vectors whose confusion matrix is known by "
      "hand, pass them through the project's own scoring path, and compare. "
      "A metric that alters its inputs fails this immediately. The second is "
      "that stored result files should be checked for internal consistency "
      "against the corpus they claim to describe — a confusion matrix whose "
      "entries do not sum to a possible test-partition size, or an accuracy "
      "quoted to more significant figures than the sample size can support, "
      "is evidence of a computation that did not occur. Both checks found "
      "defects in the material examined here, and neither requires access "
      "to anything beyond the released repository.")
    p("What this literature does not directly address is the case found "
      "here, where the defect is neither leakage nor optimistic protocol "
      "design but a modification to the scoring function itself. That case "
      "is qualitatively worse, because every methodological safeguard the "
      "above literature recommends operates on the protocol and none of them "
      "inspects the metric. A study can use nested cross-validation "
      "faithfully, hold out its test set scrupulously, permute its labels "
      "conscientiously — and still report fabricated numbers, if the "
      "function computing the confusion matrix has been altered. The "
      "practical conclusion, and one of the recommendations of this paper, "
      "is that verifying the metric implementation against a reference "
      "library on synthetic inputs with known confusion matrices should be a "
      "routine step in any reproduction attempt.")

