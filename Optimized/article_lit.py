    p("The corpus in this project contains fifty videos. That number governs "
      "what any experiment on it can establish, and the methodological "
      "literature on small-sample evaluation is therefore not a "
      "supplementary concern but the central one.")
    p(citet("varoquaux") + " measured the sampling distribution of "
      "cross-validated accuracy directly and found error bars of tens of "
      "percentage points at sample sizes typical of neuroimaging studies, "
      "concluding that cross-validation on small samples produces estimates "
      "too noisy to rank methods. " + citet("vabalas") + " reached the same "
      "conclusion for clinical prediction and showed additionally that "
      "several commonly used validation schemes produce biased estimates at "
      "small n even when applied as intended. " + citet("bouthillier") + " "
      "showed that the variance introduced by nuisance factors — "
      "initialisation seed, data ordering, augmentation randomness — "
      "typically exceeds the improvements claimed in benchmark papers, and "
      "recommended reporting across many such sources of variation.")
    p(citet("combrisson") + " addressed the specific and frequently "
      "overlooked question of what chance means. On small or imbalanced "
      "samples the empirical distribution of accuracy under a true null "
      "hypothesis is wide and centred above the nominal chance rate, so "
      "comparing an observed score to 50% is not a test. "
      + citet("ojala") + " gave the corresponding remedy: permute the "
      "labels, re-run the complete procedure, and compare the observed "
      "score to the resulting empirical null. This paper uses that test "
      "throughout, with 200 permutations of the full nested procedure.")
    p(citet("brodersen") + " analysed balanced accuracy and its posterior "
      "distribution, showing that on imbalanced data plain accuracy is "
      "systematically optimistic and that the balanced form is the "
      "appropriate summary. " + citet("he_imbalance") + " surveys learning "
      "from imbalanced data more broadly, and " + citet("saito") + " "
      "demonstrates that precision-recall analysis is more informative than "
      "ROC analysis when the positive class is rare. These matter acutely "
      "here: on a 29/21 corpus a classifier that answers 'authentic' for "
      "every input scores 58% accuracy and an F1 above 73, numbers that read "
      "as a working detector and are produced by a model that has learned "
      "nothing. Section 5 therefore reports specificity and balanced "
      "accuracy beside every accuracy figure, precisely so that this failure "
      "mode is visible rather than hidden.")
    p(citet("hanley") + " established the interpretation of the area under "
      "the ROC curve as the probability that a randomly chosen positive "
      "outranks a randomly chosen negative, together with its standard "
      "error — the basis for the accuracy ceiling computed in Section 5.6. "
      + citet("demsar") + " set out how classifiers should be compared "
      "across multiple datasets, and his central warning applies directly to "
      "single-corpus studies: differences smaller than the resampling noise "
      "are not findings.")

